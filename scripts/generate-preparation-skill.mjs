import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

import { format, resolveConfig } from 'prettier';

const root = fileURLToPath(new URL('../', import.meta.url));
const source = path.join(root, 'skills/1mcp-preparation-setup');
const target = path.join(root, 'src/commands/cliSetup/preparationSkill.generated.ts');

async function collect(directory, prefix = '') {
  const files = {};
  for (const entry of (await readdir(directory, { withFileTypes: true })).sort((a, b) =>
    a.name.localeCompare(b.name),
  )) {
    const relative = prefix + entry.name;
    if (entry.isDirectory()) {
      Object.assign(files, await collect(path.join(directory, entry.name), relative + '/'));
    } else if (entry.isFile()) {
      files[relative] = await readFile(path.join(directory, entry.name), 'utf8');
    } else {
      throw new Error(`Unsupported skill entry: ${relative}`);
    }
  }
  return files;
}

const files = await collect(source);
if (!files['SKILL.md']) throw new Error('Preparation skill entrypoint is missing');
const output = await format(
  '// Generated by scripts/generate-preparation-skill.mjs. Edit skills/1mcp-preparation-setup instead.\n' +
    `export const preparationSkillFiles: Readonly<Record<string, string>> = ${JSON.stringify(files)};\n`,
  { ...(await resolveConfig(target)), parser: 'typescript' },
);
if (process.argv.includes('--check')) {
  if ((await readFile(target, 'utf8')) !== output) throw new Error('Preparation skill bundle is stale; regenerate it');
} else {
  await writeFile(target, output);
}
